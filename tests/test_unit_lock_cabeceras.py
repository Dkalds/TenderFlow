"""La cabecera de cada lockfile es un comando que Renovate sabe volver a ejecutar.

Renovate recompila ``requirements*.txt`` ejecutando el comando que encuentra en
su cabecera (``renovate.json``, manager ``pip-compile``). Su parser admite un
subconjunto de las opciones de ``uv pip compile`` y exige ``=`` en las que
llevan valor. Con ``-o``, ``--python-platform`` o ``--system-certs`` en la
cabecera —lo que escribían ``make lock`` y Dependabot hasta 2026-10— descarta
el fichero con «Option … not supported (yet)» y deja de proponer
actualizaciones de Python sin que ningún check lo diga.

Si este test falla tras recompilar a mano o tras un PR de seguridad de
Dependabot: ``make lock`` reescribe las cinco cabeceras en el formato bueno.
"""

from __future__ import annotations

from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]

CABECERAS = {
    "requirements.txt": (
        "uv pip compile requirements.in --output-file=requirements.txt"
        " --generate-hashes --python-version=3.13"
    ),
    "requirements-dev.txt": (
        "uv pip compile requirements-dev.in --output-file=requirements-dev.txt"
        " --generate-hashes --python-version=3.13"
    ),
    "requirements-api.txt": (
        "uv pip compile requirements-api.in --output-file=requirements-api.txt"
        " --constraint=requirements.txt --generate-hashes --python-version=3.13"
    ),
    "requirements-pipeline.txt": (
        "uv pip compile requirements-pipeline.in --output-file=requirements-pipeline.txt"
        " --constraint=requirements.txt --generate-hashes --python-version=3.13"
    ),
    "requirements-mcp.txt": (
        "uv pip compile requirements-mcp.in --output-file=requirements-mcp.txt"
        " --constraint=requirements.txt --generate-hashes --python-version=3.13"
    ),
}


@pytest.mark.parametrize("lockfile", sorted(CABECERAS))
def test_la_cabecera_es_el_comando_que_renovate_admite(lockfile: str) -> None:
    lineas = (REPO / lockfile).read_text(encoding="utf-8").splitlines()
    assert lineas[0] == "# This file was autogenerated by uv via the following command:"
    assert lineas[1] == f"#    {CABECERAS[lockfile]}"


def test_make_lock_escribe_esa_cabecera() -> None:
    """``make lock`` compila con la plataforma fijada pero no la deja en la cabecera."""
    makefile = (REPO / "Makefile").read_text(encoding="utf-8")
    assert "--custom-compile-command" in makefile
    assert (
        "lock_cmd = uv pip compile $(1) --output-file=$(2) $(3)"
        " --generate-hashes --python-version=3.13"
    ) in makefile
    for fuente, destino in (
        ("requirements.in", "requirements.txt,"),
        ("requirements-dev.in", "requirements-dev.txt,"),
        ("requirements-api.in", "requirements-api.txt,--constraint=requirements.txt"),
        ("requirements-pipeline.in", "requirements-pipeline.txt,--constraint=requirements.txt"),
        ("requirements-mcp.in", "requirements-mcp.txt,--constraint=requirements.txt"),
    ):
        assert f"$(call compilar_lock,{fuente},{destino})" in makefile


def test_renovate_gestiona_los_lockfiles_y_no_los_in() -> None:
    """El patrón del manager casa con los ``.txt`` compilados, que es lo que pide."""
    import json
    import re

    config = json.loads((REPO / "renovate.json").read_text(encoding="utf-8"))
    (patron,) = config["pip-compile"]["managerFilePatterns"]
    regex = re.compile(patron.strip("/"))
    for lockfile in CABECERAS:
        assert regex.search(lockfile), lockfile
    assert not regex.search("requirements.in")
    assert "pip_requirements" not in config["enabledManagers"]
