def _is_postgres() -> bool:
    return op.get_bind().dialect.name == "postgresql"


def _texto(valor: str) -> str:
    """Literal SQL de texto."""
    return "'" + valor.replace("'", "''") + "'"


def _mapa() -> list[str]:
    valores = ",\n".join(
        f"({_texto(viejo)}, {_texto(nuevo)}, {_texto(organo)})"
        for viejo, nuevo, organo in _MAPA_DATOS
    )
    return [
        f"DROP TABLE IF EXISTS {_MAPA}",
        f"CREATE TEMP TABLE {_MAPA} "
        "(viejo text PRIMARY KEY, nuevo text NOT NULL, organo text NOT NULL)",
        f"INSERT INTO {_MAPA} (viejo, nuevo, organo) VALUES\n{valores}",
        f"""
DO $$
DECLARE
    sin_fila bigint;
BEGIN
    DELETE FROM {_MAPA} m
    WHERE NOT EXISTS (SELECT 1 FROM licitaciones l WHERE l.id_externo = m.viejo);
    GET DIAGNOSTICS sin_fila = ROW_COUNT;
    IF sin_fila > 0 THEN
        RAISE NOTICE 'v167: % claves del mapa ya no existen y se ignoran', sin_fila;
    END IF;
END
$$""",
        f"CREATE INDEX ON {_MAPA} (nuevo)",
        f"ANALYZE {_MAPA}",
    ]


def _guardas() -> str:
    cubiertas = ", ".join(_texto(f"{t}.{c}") for t, c, _ in _REFERENCIAS)
    return f"""
DO $$
DECLARE
    repetidas bigint;
    con_usuario text;
    sin_cubrir text;
    trabajos bigint;
BEGIN
    SELECT count(*) - count(DISTINCT nuevo) INTO repetidas FROM {_MAPA};
    IF repetidas > 0 THEN
        RAISE EXCEPTION 'v167: % claves correctas repetidas en el mapa', repetidas;
    END IF;

    SELECT string_agg(m.nuevo, ', ') INTO con_usuario
    FROM {_MAPA} m
    WHERE EXISTS (SELECT 1 FROM licitaciones l WHERE l.id_externo = m.nuevo)
      AND (EXISTS (SELECT 1 FROM pursuits p WHERE p.licitacion_id = m.nuevo)
           OR EXISTS (SELECT 1 FROM follows f
                      WHERE f.target_type = 'licitacion' AND f.target_id = m.nuevo)
           OR EXISTS (SELECT 1 FROM watchlist_items w WHERE w.id_externo = m.nuevo));
    IF con_usuario IS NOT NULL THEN
        RAISE EXCEPTION
            'v167: destinos ocupados con datos de usuario (pursuits, follows o watchlist), '
            'decídalos a mano: %', con_usuario;
    END IF;

    SELECT string_agg(r.relname || '.' || a.attname, ', ') INTO sin_cubrir
    FROM pg_constraint c
    JOIN pg_class r ON r.oid = c.conrelid
    JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
    WHERE c.contype = 'f' AND c.confrelid = 'licitaciones'::regclass
      AND r.relname || '.' || a.attname <> ALL (ARRAY[{cubiertas}]);
    IF sin_cubrir IS NOT NULL THEN
        RAISE EXCEPTION 'v167: FK a licitaciones sin repuntar: %', sin_cubrir;
    END IF;

    SELECT count(DISTINCT j.id) INTO trabajos
    FROM jobs j JOIN {_MAPA} m
      ON strpos(j.payload_json, to_json(m.viejo)::text) > 0
      OR strpos(j.payload_json, to_json(m.nuevo)::text) > 0
    WHERE j.estado IN ('pending', 'running');
    IF trabajos > 0 THEN
        RAISE EXCEPTION
            'v167: % trabajos pendientes en jobs nombran una licitación del mapa', trabajos;
    END IF;
END
$$"""


def _borrar_ocupados() -> list[str]:
    """Los duplicados que la ingesta escribió ya con la clave correcta."""
    ocupados = f"(SELECT m.nuevo FROM {_MAPA} m JOIN licitaciones l ON l.id_externo = m.nuevo)"
    return [
        f"UPDATE resoluciones_recurso SET licitacion_id = NULL WHERE licitacion_id IN {ocupados}",
        f"DELETE FROM mat_clusters WHERE id_externo IN {ocupados}",
        f"DELETE FROM feature_store WHERE entity_type = 'licitacion' AND entity_id IN {ocupados}",
        f"DELETE FROM licitaciones WHERE id_externo IN {ocupados}",
    ]


def _copia() -> str:
    """Copia de cada fila con su clave correcta y el órgano más reciente."""
    return f"""
DO $$
DECLARE
    destino text;
    origen text;
BEGIN
    SELECT string_agg(quote_ident(attname), ', ' ORDER BY attnum),
           string_agg('l.' || quote_ident(attname), ', ' ORDER BY attnum)
    INTO destino, origen
    FROM pg_attribute
    WHERE attrelid = 'licitaciones'::regclass AND attnum > 0 AND NOT attisdropped
      AND attgenerated = '' AND attname NOT IN ('id_externo', 'organo_ref_fuente');
    EXECUTE format(
        'INSERT INTO licitaciones (id_externo, organo_ref_fuente, %s) '
        'SELECT m.nuevo, m.organo, %s FROM licitaciones l JOIN {_MAPA} m ON l.id_externo = m.viejo',
        destino, origen
    );
END
$$"""


def _alias() -> str:
    return (
        "INSERT INTO licitaciones_id_anterior (id_anterior, id_externo, motivo, creado_en) "
        f"SELECT m.viejo, m.nuevo, {_texto(MOTIVO)}, "
        "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS\"+00:00\"') "
        f"FROM {_MAPA} m "
        "ON CONFLICT (id_anterior) DO UPDATE SET id_externo = EXCLUDED.id_externo, "
        "motivo = EXCLUDED.motivo, creado_en = EXCLUDED.creado_en"
    )


def _repunte(tabla: str, columna: str, filtro: str) -> str:
    extra = f" AND t.{filtro}" if filtro else ""
    return (
        f"UPDATE {tabla} t SET {columna} = m.nuevo FROM {_MAPA} m "
        f"WHERE t.{columna} = m.viejo{extra}"
    )


def _payload_pendiente(clave: str) -> str:
    return (
        "UPDATE domain_events d "
        f"SET payload_json = jsonb_set(d.payload_json::jsonb, '{{{clave}}}', "
        "to_jsonb(m.nuevo))::text "
        f"FROM {_MAPA} m "
        "WHERE d.dispatched_at IS NULL AND d.payload_json LIKE '{%' "
        f"AND (d.payload_json::jsonb ->> {_texto(clave)}) = m.viejo"
    )


def _sin_referencias_viejas() -> str:
    consultas = " UNION ALL ".join(
        f"SELECT {_texto(f'{t}.{c}')} AS ref, count(*) AS n FROM {t} x "
        f"JOIN {_MAPA} m ON x.{c} = m.viejo" + (f" WHERE x.{f}" if f else "")
        for t, c, f in _REFERENCIAS
    )
    return f"""
DO $$
DECLARE
    quedan text;
BEGIN
    SELECT string_agg(ref || '=' || n, ', ') INTO quedan
    FROM ({consultas}) r WHERE n > 0;
    IF quedan IS NOT NULL THEN
        RAISE EXCEPTION 'v167: referencias sin repuntar a claves antiguas: %', quedan;
    END IF;
END
$$"""


def sentencias_upgrade() -> list[str]:
    """Las sentencias de :func:`upgrade`, en orden (los tests las reaplican)."""
    return [
        "SET LOCAL statement_timeout = 0",
        "SET LOCAL lock_timeout = '30s'",
        "SET LOCAL row_security = off",
        *_mapa(),
        _guardas(),
        # Antes de borrar: el borrado en cascada toca licitacion_tecnologia_score y
        # su trigger diferido dejaría eventos pendientes que impiden desactivarlo.
        f"ALTER TABLE licitacion_tecnologia_score DISABLE TRIGGER {_TRIGGER_LTS}",
        *_borrar_ocupados(),
        _copia(),
        _alias(),
        *(_repunte(t, c, f) for t, c, f in _REFERENCIAS),
        *(_payload_pendiente(clave) for clave in _CLAVES_PAYLOAD),
        _sin_referencias_viejas(),
        f"DELETE FROM licitaciones l USING {_MAPA} m WHERE l.id_externo = m.viejo",
        f"ALTER TABLE licitacion_tecnologia_score ENABLE TRIGGER {_TRIGGER_LTS}",
        f"DROP TABLE {_MAPA}",
    ]


def upgrade() -> None:
    if not _is_postgres():
        return
    for sentencia in sentencias_upgrade():
        op.execute(sentencia)


def downgrade() -> None:
    """No hay vuelta atrás automática: la clave antigua recrearía los duplicados.

    El mapa inverso queda en ``licitaciones_id_anterior`` (``motivo =
    'rekey_placsp_organo_reciente'``).
    """
    return
